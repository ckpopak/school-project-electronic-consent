CREATE TABLE school (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    code VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    school_id BIGINT,
    CONSTRAINT fk_user_school FOREIGN KEY (school_id) REFERENCES school(id)
);

CREATE TABLE student (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guardian_id BIGINT NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    class_name VARCHAR(50),
    class_number VARCHAR(10),
    CONSTRAINT fk_student_guardian FOREIGN KEY (guardian_id) REFERENCES app_user(id)
);

CREATE TABLE campaign (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(2000),
    qr_token VARCHAR(64) NOT NULL UNIQUE,
    starts_at TIMESTAMP NOT NULL,
    deadline_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_campaign_school FOREIGN KEY (school_id) REFERENCES school(id)
);

CREATE TABLE consent_submission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    decision VARCHAR(20) NOT NULL,
    scope_note VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED',
    submitted_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_campaign_student UNIQUE (campaign_id, student_id),
    CONSTRAINT fk_submission_campaign FOREIGN KEY (campaign_id) REFERENCES campaign(id),
    CONSTRAINT fk_submission_student FOREIGN KEY (student_id) REFERENCES student(id)
);
